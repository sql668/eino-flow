-- 0001_init：EinoFlow V0.1 基础表结构
--
-- 约定：
--   * 时间统一用 timestamptz（绝对时刻），不做时区转换也不会错；
--   * 软删除统一用 deleted_at（NULL 表示未删除）；
--   * updated_at 由应用层维护（GORM 的 UpdatedAt）。PostgreSQL 没有
--     ON UPDATE CURRENT_TIMESTAMP，手写 SQL 更新时需自己带上；
--   * 不建外键：外键会让软删除与后续分表演进变复杂，关联完整性由应用层保证；
--   * 脚本必须可重复执行，便于迁移中途失败后重跑（PostgreSQL 支持事务性 DDL，
--     正常情况下不会留下半成品结构）。

CREATE TABLE IF NOT EXISTS apps (
  id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        VARCHAR(128) NOT NULL,
  description VARCHAR(512) NOT NULL DEFAULT '',
  mode        VARCHAR(32)  NOT NULL,                  -- chat / rag / agent / workflow
  status      VARCHAR(32)  NOT NULL DEFAULT 'draft',  -- draft / published
  icon        VARCHAR(255) NOT NULL DEFAULT '',
  created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
  updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
  deleted_at  TIMESTAMPTZ
);

COMMENT ON TABLE apps IS 'AI 应用';

CREATE INDEX IF NOT EXISTS idx_apps_mode ON apps (mode);

CREATE INDEX IF NOT EXISTS idx_apps_deleted_at ON apps (deleted_at);

CREATE TABLE IF NOT EXISTS datasets (
  id              BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name            VARCHAR(128) NOT NULL,
  description     VARCHAR(512) NOT NULL DEFAULT '',
  embedding_model VARCHAR(128) NOT NULL DEFAULT '',      -- 换模型后需重建索引
  status          VARCHAR(32)  NOT NULL DEFAULT 'active', -- active / indexing / error
  created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
  updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
  deleted_at      TIMESTAMPTZ
);

COMMENT ON TABLE datasets IS '知识库';

CREATE INDEX IF NOT EXISTS idx_datasets_deleted_at ON datasets (deleted_at);

CREATE TABLE IF NOT EXISTS documents (
  id            BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dataset_id    BIGINT       NOT NULL,
  name          VARCHAR(255) NOT NULL,
  source        VARCHAR(512) NOT NULL DEFAULT '',  -- 原始文件在对象存储中的 key
  file_size     BIGINT       NOT NULL DEFAULT 0 CHECK (file_size >= 0),
  status        VARCHAR(32)  NOT NULL DEFAULT 'pending',  -- pending / indexing / ready / failed
  segment_count INTEGER      NOT NULL DEFAULT 0 CHECK (segment_count >= 0),
  error_message VARCHAR(512) NOT NULL DEFAULT '',
  created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
  updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
  deleted_at    TIMESTAMPTZ
);

COMMENT ON TABLE documents IS '知识库文档';

CREATE INDEX IF NOT EXISTS idx_documents_dataset ON documents (dataset_id);

CREATE INDEX IF NOT EXISTS idx_documents_status ON documents (status);

CREATE INDEX IF NOT EXISTS idx_documents_deleted_at ON documents (deleted_at);

CREATE TABLE IF NOT EXISTS document_segments (
  id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dataset_id  BIGINT       NOT NULL,
  document_id BIGINT       NOT NULL,
  chunk_index INTEGER      NOT NULL CHECK (chunk_index >= 0),  -- 在文档中的顺序，从 0 开始
  content     TEXT         NOT NULL,
  token_count INTEGER      NOT NULL DEFAULT 0 CHECK (token_count >= 0),
  vector_id   VARCHAR(128) NOT NULL DEFAULT '',  -- Milvus 中的向量主键，便于删除与重建
  created_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);

COMMENT ON TABLE document_segments IS '文档分段（向量存 Milvus）';

CREATE INDEX IF NOT EXISTS idx_segments_document ON document_segments (document_id, chunk_index);

CREATE INDEX IF NOT EXISTS idx_segments_dataset ON document_segments (dataset_id);

CREATE TABLE IF NOT EXISTS conversations (
  id         BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  app_id     BIGINT       NOT NULL,
  title      VARCHAR(255) NOT NULL DEFAULT '',
  user_id    VARCHAR(64)  NOT NULL DEFAULT '',  -- V0.1 暂无多用户体系，预留
  created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);

COMMENT ON TABLE conversations IS '会话';

CREATE INDEX IF NOT EXISTS idx_conversations_app ON conversations (app_id);

CREATE TABLE IF NOT EXISTS messages (
  id              BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversation_id BIGINT      NOT NULL,
  role            VARCHAR(32) NOT NULL,  -- system / user / assistant / tool
  content         TEXT        NOT NULL,
  token_count     INTEGER     NOT NULL DEFAULT 0 CHECK (token_count >= 0),
  latency_ms      INTEGER     NOT NULL DEFAULT 0 CHECK (latency_ms >= 0),
  trace_id        VARCHAR(64) NOT NULL DEFAULT '',  -- 链路追踪 ID，V2.0 可观测使用
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE messages IS '会话消息';

CREATE INDEX IF NOT EXISTS idx_messages_conversation ON messages (conversation_id, id);
