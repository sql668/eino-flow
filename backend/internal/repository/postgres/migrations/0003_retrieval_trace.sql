-- 0003_retrieval_trace：检索留痕
--
-- 背景（见 docs/PROGRESS.md D6）：检索质量问题属于「事后想复现却复现不出来」的典型场景，
-- 记录不留就无法补，因此即使重排（rerank）与可视化页面尚未落地，这里也要先把表建好。
--
-- 结构说明：
--   * retrieval_runs 记录「问过什么、用哪个模型、花了多久、返回几条」；
--   * retrieval_hits 记录「命中了哪些片段、排第几、分数多少」；
--   * stage 字段区分召回与重排两个阶段：重排落地后同一片段会有两条记录，
--     「召回 20 条 → 重排后留 5 条」的完整过程才可回溯；
--   * rerank_score 允许为空，表示该阶段还没有重排分数（不能用 0 代替，0 是有意义的分数）。

CREATE TABLE IF NOT EXISTS retrieval_runs (
  id              BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dataset_id      BIGINT       NOT NULL,
  query           TEXT         NOT NULL,
  top_k           INTEGER      NOT NULL DEFAULT 0,
  embedding_model VARCHAR(128) NOT NULL DEFAULT '',
  latency_ms      INTEGER      NOT NULL DEFAULT 0,
  hit_count       INTEGER      NOT NULL DEFAULT 0,
  error_message   VARCHAR(512) NOT NULL DEFAULT '',
  created_at      TIMESTAMPTZ  NOT NULL DEFAULT now()
);

COMMENT ON TABLE retrieval_runs IS '检索请求记录（每次检索一条）';

COMMENT ON COLUMN retrieval_runs.embedding_model IS '本次检索使用的向量模型，换模型后用于解释结果差异';

COMMENT ON COLUMN retrieval_runs.error_message IS '失败原因；成功为空。失败的检索同样要留痕';

-- 检索历史按知识库 + 时间倒序查询，索引按同样的顺序建。
CREATE INDEX IF NOT EXISTS idx_retrieval_runs_dataset_created
  ON retrieval_runs (dataset_id, created_at DESC);

CREATE TABLE IF NOT EXISTS retrieval_hits (
  id           BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id       BIGINT       NOT NULL,
  dataset_id   BIGINT       NOT NULL,
  segment_id   BIGINT       NOT NULL,
  document_id  BIGINT       NOT NULL,
  rank         INTEGER      NOT NULL DEFAULT 0,
  score        REAL         NOT NULL DEFAULT 0,
  rerank_score REAL,
  stage        VARCHAR(16)  NOT NULL DEFAULT 'vector',
  created_at   TIMESTAMPTZ  NOT NULL DEFAULT now()
);

COMMENT ON TABLE retrieval_hits IS '检索命中片段（一次检索可有多条）';

COMMENT ON COLUMN retrieval_hits.rank IS '该片段在本阶段的排名，从 1 开始';

COMMENT ON COLUMN retrieval_hits.score IS '向量相似度（余弦，越大越相似）';

COMMENT ON COLUMN retrieval_hits.rerank_score IS '重排分数；为空表示尚未经过重排';

COMMENT ON COLUMN retrieval_hits.stage IS '命中发生的阶段：vector 召回 / rerank 重排';

CREATE INDEX IF NOT EXISTS idx_retrieval_hits_run ON retrieval_hits (run_id, rank);

CREATE INDEX IF NOT EXISTS idx_retrieval_hits_segment ON retrieval_hits (segment_id);
