-- 0004_model_config：模型配置（内置厂商 + 凭证 + 模型 + 绑定）
--
-- 设计（见 docs/PROGRESS.md D3、D8）：
--   * 厂商是**代码**（internal/engine/model/providers），这里只存用户为该厂商填的
--     base_url 与凭证；因此 model_providers.provider 存的是厂商标识，不是外键表；
--   * 凭证**只存密文**（AES-256-GCM，密钥来自环境变量），列名直接叫 credentials 而不是
--     api_key：将来一个厂商需要多个字段（key + secret）时不必改表；
--   * 模型（model_instances）与厂商实例分开：同一个凭证下会有多个模型，
--     凭证改了不必逐个改模型；
--   * 绑定（model_bindings）用一张表同时表达「全局默认」「应用覆盖」「知识库覆盖」，
--     靠 scope 区分。分三张表会让「取生效模型」退化成三段 if-else。

CREATE TABLE IF NOT EXISTS model_providers (
  id           BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider     VARCHAR(64)  NOT NULL,               -- 内置厂商标识：ollama / openai_compatible / tei
  display_name VARCHAR(128) NOT NULL DEFAULT '',    -- 展示名，留空时用厂商的默认名
  base_url     VARCHAR(255) NOT NULL DEFAULT '',    -- 留空时用厂商的默认地址
  credentials  TEXT         NOT NULL DEFAULT '',    -- AES-256-GCM 密文；空串表示尚未填凭证
  enabled      BOOLEAN      NOT NULL DEFAULT TRUE,
  created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
  updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now()
);

COMMENT ON TABLE model_providers IS '模型厂商凭证配置（一个厂商一条）';

COMMENT ON COLUMN model_providers.provider IS '内置厂商标识，取值由代码定义（见 providers 注册表）';

COMMENT ON COLUMN model_providers.credentials IS '凭证密文（AES-256-GCM），绝不存明文、绝不回明文';

-- 一个厂商只允许一条配置：多个同厂商端点属于「新增一个厂商」而不是「同厂商多份凭证」，
-- 否则「用哪个凭证」这件事会变成每次调用都要选的隐式状态。
CREATE UNIQUE INDEX IF NOT EXISTS uk_model_providers_provider ON model_providers (provider);

CREATE TABLE IF NOT EXISTS model_instances (
  id           BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider_id  BIGINT       NOT NULL,
  model_name   VARCHAR(128) NOT NULL,               -- 传给服务端的模型名，如 bge-m3:latest
  model_type   VARCHAR(32)  NOT NULL,               -- llm / embedding / rerank
  display_name VARCHAR(128) NOT NULL DEFAULT '',
  enabled      BOOLEAN      NOT NULL DEFAULT TRUE,
  created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
  updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now()
);

COMMENT ON TABLE model_instances IS '可用模型（同一厂商凭证下的模型清单）';

COMMENT ON COLUMN model_instances.model_type IS '模型能力类型：llm 对话 / embedding 向量化 / rerank 重排';

-- 同一厂商下同类型同名模型只允许一条，避免列表里出现两个「看起来一样」的条目。
CREATE UNIQUE INDEX IF NOT EXISTS uk_model_instances_provider_model
  ON model_instances (provider_id, model_type, model_name);

CREATE INDEX IF NOT EXISTS idx_model_instances_type ON model_instances (model_type);

CREATE TABLE IF NOT EXISTS model_bindings (
  id                BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  scope             VARCHAR(16) NOT NULL,           -- global / app / dataset
  app_id            BIGINT      NOT NULL DEFAULT 0, -- scope=app 时有值
  dataset_id        BIGINT      NOT NULL DEFAULT 0, -- scope=dataset 时有值
  model_type        VARCHAR(32) NOT NULL,
  model_instance_id BIGINT      NOT NULL,
  created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE model_bindings IS '模型绑定：全局默认 / 应用覆盖 / 知识库覆盖';

COMMENT ON COLUMN model_bindings.scope IS 'global 全局 / app 应用覆盖 / dataset 知识库覆盖';

-- 同一作用域同一类型只能绑一个模型；重复绑定用 upsert 覆盖，保证「取生效模型」永远有唯一答案。
CREATE UNIQUE INDEX IF NOT EXISTS uk_model_bindings_scope
  ON model_bindings (scope, app_id, dataset_id, model_type);

CREATE INDEX IF NOT EXISTS idx_model_bindings_instance ON model_bindings (model_instance_id);
