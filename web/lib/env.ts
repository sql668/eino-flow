// 统一读取前端环境变量，避免在业务代码里散落 process.env 访问。
// 约定：只有 NEXT_PUBLIC_ 前缀的变量会被打包进浏览器端代码。

/**
 * 后端 API 基础地址。
 *
 * 默认为空字符串，表示「同源」：请求发给当前站点，再由 Next 的 rewrites（开发 / 隧道演示）
 * 或 Nginx（生产）转发到后端。
 *
 * 之所以不用 http://127.0.0.1:8888 作为默认值：NEXT_PUBLIC_ 变量会在构建时写死进产物，
 * 浏览器解析 127.0.0.1 指的是「访问者自己的机器」，部署到公网后必然请求失败。
 * 仅在前后端确实分离部署、且已验证跨域配置时才需要显式设置。
 */
export const API_BASE_URL = process.env.NEXT_PUBLIC_API_BASE_URL ?? "";
